-- هر دو تغییر «شل‌کننده» (relaxing) هستند: هیچ دادهٔ موجودی نقض نمی‌شود و
-- هیچ Backfill دستی لازم نیست.

-- DropIndex
-- موبایل دیگر یکتا نیست: یک شماره واقعاً می‌تواند برای چند مشتری ثبت شود (مثلاً
-- چند شرکت با یک نمایندهٔ واحد، یا مشتری حقیقی و حقوقیِ یک شخص). یکتایی هویت
-- مشتری با `nationalId`/`customerCode` است، نه با شمارهٔ تماس.
-- ⚠️ این ایندکس یکتا حذف می‌شود، نه ستون؛ خودِ ستون `mobile` دست‌نخورده و
-- NOT NULL می‌ماند و اعتبارسنجی «قالب شماره» (۰۹xxxxxxxxx) سر جای خود است.
DROP INDEX "Customer_mobile_key";

-- AlterTable
-- کد تفصیل اختیاری می‌شود: در لحظهٔ ثبت مشتری همیشه در دسترس نیست و بعداً از ERP
-- تکمیل می‌شود؛ تا آن زمان `null` می‌ماند (نه رشتهٔ خالی — رشتهٔ خالی در ایندکس
-- یکتا فقط برای یک مشتری جا داشت و ثبت مشتری دومِ بدون کد را می‌شکست).
-- ایندکس یکتای `Customer_customerCode_key` عمداً باقی می‌ماند: Postgres چند مقدار
-- NULL را در ایندکس یکتا می‌پذیرد، پس چند مشتریِ بدون کد تفصیل هم‌زمان مجازند در
-- حالی که یکتایی کدهای واقعی همچنان تضمین شده است.
ALTER TABLE "Customer" ALTER COLUMN "customerCode" DROP NOT NULL;
